/** Returns numbers in [0, 1). All randomness in the rules comes through one of these. */
export type Rng = () => number;

/** Small seeded generator (mulberry32), so a fight can be replayed exactly. */
export function seeded(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
